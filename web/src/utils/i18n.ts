// Language state - synced with uiStore
let currentLang: Lang = 'tr';

export function setLanguage(lang: Lang) {
  currentLang = lang;
  if (typeof window !== 'undefined') {
    localStorage.setItem('lc.language', lang);
  }
}

export function getLanguage(): Lang {
  return currentLang;
}

export function initLanguage(): Lang {
  if (typeof window !== 'undefined') {
    const saved = localStorage.getItem('lc.language') as Lang | null;
    if (saved === 'tr' || saved === 'en') {
      currentLang = saved;
      return saved;
    }
  }
  return 'tr';
}

/**
 * Translate a key to the current language.
 * Falls back to English, then returns the key itself.
 */
export function t(key: string, params?: Record<string, string | number>): string {
  let result = translations[currentLang]?.[key] ?? translations['en']?.[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      result = result.replace(`{${k}}`, String(v));
    }
  }
  return result;
}

/**
 * Translate with explicit language.
 */
export function tLang(key: string, lang: Lang, params?: Record<string, string | number>): string {
  let result = translations[lang]?.[key] ?? translations['en']?.[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      result = result.replace(`{${k}}`, String(v));
    }
  }
  return result;
}
